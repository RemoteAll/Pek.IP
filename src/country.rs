/// 常见中文国家名 → ISO 代码（用于 ip2region 旧格式等缺少 ISO 字段的场景）。
pub fn country_code_from_name(name: &str) -> Option<&'static str> {
    Some(match name.trim() {
        "中国" | "中华人民共和国" => "CN",
        "美国" => "US",
        "日本" => "JP",
        "韩国" => "KR",
        "朝鲜" => "KP",
        "英国" => "GB",
        "德国" => "DE",
        "法国" => "FR",
        "俄罗斯" => "RU",
        "加拿大" => "CA",
        "澳大利亚" => "AU",
        "新西兰" => "NZ",
        "新加坡" => "SG",
        "马来西亚" => "MY",
        "印度尼西亚" | "印尼" => "ID",
        "菲律宾" => "PH",
        "泰国" => "TH",
        "越南" => "VN",
        "印度" => "IN",
        "巴基斯坦" => "PK",
        "孟加拉国" => "BD",
        "巴西" => "BR",
        "阿根廷" => "AR",
        "墨西哥" => "MX",
        "智利" => "CL",
        "南非" => "ZA",
        "埃及" => "EG",
        "沙特阿拉伯" => "SA",
        "阿拉伯联合酋长国" | "阿联酋" => "AE",
        "土耳其" => "TR",
        "西班牙" => "ES",
        "意大利" => "IT",
        "荷兰" => "NL",
        "瑞士" => "CH",
        "瑞典" => "SE",
        "挪威" => "NO",
        "丹麦" => "DK",
        "芬兰" => "FI",
        "波兰" => "PL",
        "乌克兰" => "UA",
        "中国香港特别行政区" | "中国香港" | "香港" => "HK",
        "中国澳门特别行政区" | "中国澳门" | "澳门" => "MO",
        "台湾" | "中国台湾" => "TW",
        _ => return None,
    })
}

/// 洲代码 → 简体中文名。
pub fn continent_name_zh(code: &str) -> Option<&'static str> {
    Some(match code.trim().to_ascii_uppercase().as_str() {
        "AF" => "非洲",
        "AN" => "南极洲",
        "AS" => "亚洲",
        "EU" => "欧洲",
        "NA" => "北美洲",
        "OC" => "大洋洲",
        "SA" => "南美洲",
        _ => return None,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn country_names() {
        assert_eq!(country_name_zh("CN"), Some("中国"));
        assert_eq!(country_name_zh("us"), Some("美国"));
        assert_eq!(country_name_zh(" JP "), Some("日本"));
        assert_eq!(country_name_zh("ZZZ"), None);
        assert_eq!(country_name_zh("1A"), None);
    }

    #[test]
    fn reverse_names() {
        assert_eq!(country_code_from_name("中国"), Some("CN"));
        assert_eq!(country_code_from_name("美国"), Some("US"));
        assert_eq!(country_code_from_name("不存在"), None);
    }

    #[test]
    fn continents() {
        assert_eq!(continent_name_zh("AS"), Some("亚洲"));
        assert_eq!(continent_name_zh("na"), Some("北美洲"));
        assert_eq!(continent_name_zh("XX"), None);
    }
}
